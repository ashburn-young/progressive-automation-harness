async function exportSkill() {
  if (!state.taskName) return toast("Pick or generate a workflow first.");
  try {
    const res = await api(`/api/skill-artifact?name=${encodeURIComponent(state.taskName)}`);
    if (!res.exists) {
      toast("No skill yet. Run or simulate this workflow first.");
      return;
    }
    const blob = new Blob([res.json], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${res.task_name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}.skill.json`;
    a.click();
    URL.revokeObjectURL(url);
    toast("Skill exported as JSON.");
  } catch (e) {
    toast("Export failed: " + e.message);
  }
}

