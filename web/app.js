// app.js - drives the Progressive Automation Harness UI against the FastAPI backend.

const $ = (id) => document.getElementById(id);
const api = (path, opts) =>
  fetch(path, { headers: { "Content-Type": "application/json" }, ...opts }).then(
    async (r) => {
      if (!r.ok) throw new Error((await r.json().catch(() => ({}))).detail || r.statusText);
      return r.json();
    }
  );

let state = {
  demo: null,
  schema: null,
  sessionId: null,
  taskName: "",
  detail: "balanced",
  model: "auto",
  mode: "describe",
  interviewId: null,
};

// ---------- helpers ----------
function toast(msg, ms = 2600) {
  const t = $("toast");
  t.textContent = msg;
  t.hidden = false;
  clearTimeout(toast._t);
  toast._t = setTimeout(() => (t.hidden = true), ms);
}

function sourceBadge(source) {
  if (!source) return "";
  if (source.startsWith("skill")) return `<span class="badge skill">${source}</span>`;
  if (source === "llm") return `<span class="badge llm">llm</span>`;
  return `<span class="badge mock">${source}</span>`;
}

function busy(btn, on, label) {
  if (!btn) return;
  if (on) {
    btn.dataset.label = btn.innerHTML;
    btn.disabled = true;
    btn.innerHTML = `<span class="spin">◐</span> ${label || "Working…"}`;
  } else {
    btn.disabled = false;
    btn.innerHTML = btn.dataset.label || btn.innerHTML;
  }
}

// ---------- mode / health ----------
async function loadHealth() {
  try {
    const h = await api("/api/health");
    $("modeDot").className = "dot " + (h.offline ? "offline" : "online");
    $("modeText").textContent = h.offline ? "offline · mock drafts" : "live · Azure gpt-5.6-sol";
  } catch {
    $("modeText").textContent = "backend offline";
  }
}

// ---------- generate ----------
function renderPreview(schema, by, model) {
  state.schema = schema;
  state.taskName = schema.task_name;
  $("previewTask").textContent = schema.task_name;
  $("previewBy").textContent = model ? `${by || "demo"} · ${model}` : (by || "demo");
  $("previewSteps").innerHTML = schema.steps
    .map((s) => `<li><b>${s.name}</b>: ${s.description}</li>`)
    .join("");
  $("preview").hidden = false;
  // Reflect this task's learned skill (if any) in the Skill panel.
  loadSkillReport(schema.task_name);
}

async function generate() {
  const desc = $("desc").value.trim();
  if (!desc) {
    toast("Describe a task first, or pick a demo chip.");
    return;
  }
  busy($("generateBtn"), true, "Generating…");
  try {
    const res = await api("/api/generate", {
      method: "POST",
      body: JSON.stringify({ description: desc, detail: state.detail, model: state.model }),
    });
    renderPreview(res.schema, res.generated_by, res.model);
    toast(res.generated_by === "llm" ? "Workflow generated by the LLM." : "Used a demo workflow.");
  } catch (e) {
    toast("Generate failed: " + e.message);
  } finally {
    busy($("generateBtn"), false);
  }
}

// ---------- session ----------
async function ensureSchema() {
  if (state.schema) return state.schema;
  // Require an explicit selection: a picked example fills the box, or the user
  // typed a task. No implicit default, so nothing runs without a real choice.
  const typed = $("desc").value.trim();
  if (!typed) {
    toast("Pick an example or describe a task first.");
    return null;
  }
  const res = await api("/api/generate", {
    method: "POST",
    body: JSON.stringify({ description: typed, detail: state.detail, model: state.model }),
  });
  renderPreview(res.schema, res.generated_by, res.model);
  return res.schema;
}

async function startSession() {
  if (state.mode === "interview" && !state.schema) {
    toast("Answer a few questions first, or switch to Quick describe.");
    return;
  }
  busy($("startBtn"), true, "Planning…");
  try {
    const schema = await ensureSchema();
    if (!schema) return; // no selection yet; ensureSchema already prompted
    // Surface the grounded plan before stepping through it.
    busy($("startBtn"), false);
    busy($("startBtn"), true, "Starting…");
    const view = await api("/api/session", {
      method: "POST",
      body: JSON.stringify({
        workflow: schema,
        inputs: readRunInputs(),
        model: state.model,
        require_approvals: $("nyesToggle") && $("nyesToggle").checked ? 2 : 1,
      }),
    });
    state.sessionId = view.session_id;
    $("emptyStage").hidden = true;
    render(view);
    toast(`Plan ready: ${schema.steps.length} step(s). Co-pilot started.`);
  } catch (e) {
    toast("Start failed: " + e.message);
  } finally {
    busy($("startBtn"), false);
  }
}

async function decide(decision) {
  const feedback = $("feedback").value.trim();
  document.querySelectorAll(".bp-actions .btn").forEach((b) => (b.disabled = true));
  try {
    const view = await api(`/api/session/${state.sessionId}/decision`, {
      method: "POST",
      body: JSON.stringify({ decision, feedback }),
    });
    $("feedback").value = "";
    render(view);
  } catch (e) {
    toast("Decision failed: " + e.message);
    document.querySelectorAll(".bp-actions .btn").forEach((b) => (b.disabled = false));
  }
}

// Run a human-edited action verbatim; the edit becomes the learned exemplar.
async function editAndRun() {
  const action = $("editAction").value.trim();
  if (!action) {
    toast("Edit the action text first, then Edit & run.");
    return;
  }
  document.querySelectorAll(".bp-actions .btn").forEach((b) => (b.disabled = true));
  try {
    const view = await api(`/api/session/${state.sessionId}/decision`, {
      method: "POST",
      body: JSON.stringify({ decision: "edit", action }),
    });
    render(view);
  } catch (e) {
    toast("Edit failed: " + e.message);
    document.querySelectorAll(".bp-actions .btn").forEach((b) => (b.disabled = false));
  }
}

// ---------- rendering ----------
function render(view) {
  state.taskName = view.task_name;
  renderTimeline(view.history);
  renderBreakpoint(view);
  renderSkill(view.skill);
  $("doneBanner").hidden = !view.completed;
  if (view.completed) toast("Workflow complete. Skill updated.");
}

function renderTimeline(history) {
  const tl = $("timeline");
  tl.hidden = false;
  tl.innerHTML = (history || [])
    .map((e) => {
      if (e.event === "draft") {
        return `<div class="event draft">
          <div class="ev-head">✎ Drafted · step ${e.step_index + 1} · ${e.step_name} ${sourceBadge(e.source)}</div>
          <div class="ev-body">${escapeHtml(e.action)}</div>
        </div>`;
      }
      if (e.event === "human_review") {
        return `<div class="event review">
          <div class="ev-head">🙦 Reviewed <span class="badge ${e.decision}">${e.decision}</span></div>
          ${e.feedback ? `<div class="ev-body muted">“${escapeHtml(e.feedback)}”</div>` : ""}
        </div>`;
      }
      if (e.event === "execute") {
        const r = e.result || "";
        let toolBadge = "";
        if (r.startsWith("[mcp:")) {
          const m = r.match(/^\[mcp:([^\]]+)\]/);
          toolBadge = `<span class="badge mcp">mcp · ${m ? m[1] : ""}</span>`;
        } else if (r.startsWith("[browsed")) {
          toolBadge = `<span class="badge web">web</span>`;
        }
        return `<div class="event execute">
          <div class="ev-head">⚡ Executed · ${e.step_name} ${toolBadge}</div>
          <div class="ev-body">${escapeHtml(r)}</div>
        </div>`;
      }
      return "";
    })
    .join("");
  tl.scrollIntoView({ behavior: "smooth", block: "end" });
}

function renderBreakpoint(view) {
  const bp = $("breakpoint");
  if (view.status !== "awaiting_review") {
    bp.hidden = true;
    return;
  }
  const idx = view.current_step_index;
  const step = view.steps[idx];
  $("bpStep").textContent = `Step ${idx + 1} of ${view.steps.length} · ${step ? step.name : ""}`;
  $("bpAction").textContent = deDash(view.drafted_action || "");
  $("editAction").value = deDash(view.drafted_action || "");
  $("bpSource").innerHTML = sourceBadge(view.draft_source);
  // N-eyes: show co-approval status when a step needs more than one approver.
  const appr = view.approval || { required: 1, have: 0 };
  const bpAppr = $("bpApproval");
  if (bpAppr) {
    if (appr.required > 1) {
      bpAppr.hidden = false;
      bpAppr.textContent =
        `🔐 Segregation of duties: needs ${appr.required} distinct approvers ` +
        `(${appr.have}/${appr.required} so far` +
        (appr.teams ? " · Teams notified)" : ")");
    } else {
      bpAppr.hidden = true;
    }
  }
  document.querySelectorAll(".bp-actions .btn").forEach((b) => (b.disabled = false));
  bp.hidden = false;
}

// Skill-panel action buttons only work once a skill exists for the current task.
const SKILL_ACTION_IDS = ["viewJsonBtn", "promptBtn", "exportBtn", "deployBtn", "runBtn", "runInputs"];

function setSkillActionsEnabled(on) {
  SKILL_ACTION_IDS.forEach((id) => {
    const el = $(id);
    if (el) el.disabled = !on;
  });
}

// Neutral state: no task chosen yet in panel 1, so the Skill panel is generic.
function resetSkillPanel() {
  state.taskName = "";
  const badge = $("overallBadge");
  badge.textContent = "—";
  badge.dataset.level = "";
  document.querySelectorAll(".rung").forEach((r) => r.classList.remove("reached"));
  $("skillRows").innerHTML =
    `<p class="muted small">Describe a task and click Start to watch the skill form here.</p>`;
  setSkillActionsEnabled(false);
}

// Load and render the current task's learned skill (dynamic per selection).
async function loadSkillReport(name) {
  if (!name) return;
  try {
    const res = await api(`/api/skill-report?name=${encodeURIComponent(name)}`);
    renderSkill({ rows: res.rows, overall: res.overall });
  } catch (e) {
    renderSkill({ rows: [], overall: "cold" });
  }
}

// Clear all state and return the UI to a fresh, unselected session.
function newSession() {
  state.sessionId = null;
  state.schema = null;
  state.interviewId = null;
  state.demo = null;
  const desc = $("desc");
  if (desc) desc.value = "";  document.querySelectorAll(".chip").forEach((c) => c.classList.remove("active"));
  ["preview", "breakpoint", "doneBanner"].forEach((id) => {
    const el = $(id);
    if (el) el.hidden = true;
  });
  const stage = $("emptyStage");
  if (stage) stage.hidden = false;
  const tl = $("timeline");
  if (tl) {
    tl.innerHTML = "";
    tl.hidden = true;
  }
  const chat = $("chatLog");
  if (chat) chat.innerHTML = "";
  resetSkillPanel();
  setMode("describe");
  toast("New session — everything cleared.");
}

function renderSkill(skill) {
  const overall = (skill && skill.overall) || "cold";
  const badge = $("overallBadge");
  badge.textContent = overall;
  badge.dataset.level = overall;
  const order = ["cold", "primed", "deterministic", "autonomous"];
  const reachedIdx = order.indexOf(overall);
  document.querySelectorAll(".rung").forEach((r) => {
    r.classList.toggle("reached", order.indexOf(r.dataset.level) <= reachedIdx);
  });

  const rows = (skill && skill.rows) || [];
  const box = $("skillRows");
  setSkillActionsEnabled(rows.length > 0);
  if (!rows.length) {
    box.innerHTML = `<p class="muted small">No skill learned yet for this task.</p>`;
    return;
  }
  const pct = { cold: 12, primed: 40, deterministic: 72, autonomous: 100 };
  box.innerHTML = rows
    .map(
      (r) => `<div class="srow">
        <span class="name">${r.step_id}. ${escapeHtml(r.step_name)}</span>
        <span class="meta">${r.approvals} approvals${
          r.rejections ? ` · ${r.rejections} rejected` : ""
        }${r.failures ? ` · ${r.failures} failed` : ""} · ${r.maturity}</span>
        <div class="prog"><i style="width:${pct[r.maturity] || 12}%"></i></div>
      </div>`
    )
    .join("");
}

