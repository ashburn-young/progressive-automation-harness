// Render one labelled field per declared input; else show the raw JSON box + hint.
function renderRunFields(fields) {
  state.runInputs = fields || [];
  const box = $("runInputFields");
  const hint = $("runInputsHint");
  if (fields && fields.length) {
    box.hidden = false;
    box.innerHTML = fields
      .map(
        (f) => `<label class="run-field"><span>${escapeHtml(f)}</span>
          <input class="inputs-field run-arg" data-key="${escapeHtml(f)}" type="text" placeholder="${escapeHtml(f)}" /></label>`
      )
      .join("");
    $("runModalInputs").hidden = true;
    hint.hidden = true;
  } else {
    box.hidden = true;
    box.innerHTML = "";
    $("runModalInputs").hidden = false;
    hint.hidden = false;
    hint.textContent =
      'This skill declares no inputs, so it defaults to MSFT. To look up a specific stock, enter e.g. {"symbol":"MSFT"}.';
  }
}

// Build the inputs object from the labelled fields, or the raw JSON box.
function collectRunInputs() {
  const fields = state.runInputs || [];
  if (fields.length) {
    const obj = {};
    document.querySelectorAll("#runInputFields .run-arg").forEach((inp) => {
      const v = inp.value.trim();
      if (v) obj[inp.dataset.key] = v;
    });
    return obj;
  }
  return parseRunModalInputs();
}

function parseRunModalInputs() {
  const raw = ($("runModalInputs").value || "").trim();
  if (!raw) return {};
  try {
    const p = JSON.parse(raw);
    if (p && typeof p === "object" && !Array.isArray(p)) return p;
    toast("Inputs must be a JSON object; ignoring.");
  } catch (e) {
    toast("Inputs JSON is invalid; ignoring. " + e.message);
  }
  return {};
}

async function playRun() {
  const name = state.runTask;
  if (!name) return;
  const inputs = collectRunInputs();
  busy($("runPlayBtn"), true, "Running\u2026");
  const tl = $("runTimeline");
  tl.innerHTML = `<p class="muted small">Executing\u2026</p>`;
  try {
    const res = await api(`/api/skill-run?name=${encodeURIComponent(name)}`, {
      method: "POST",
      body: JSON.stringify({ inputs }),
    });
    if (!res.steps || (!res.steps.length && res.status !== "blocked")) {
      tl.innerHTML = `<p class="muted small">${escapeHtml(
        res.reason || "Nothing to run \u2014 deploy or run this skill first."
      )}</p>`;
      return;
    }
    $("runMaturity").textContent = res.overall || "\u2014";
    $("runMaturity").dataset.level = res.overall || "";
    $("runSummary").textContent = deDash(res.summary || "");
    $("runMeta").hidden = false;
    $("runMeta").innerHTML =
      `<span><b>${res.autonomous_steps}</b>/${res.total_steps} ran autonomously</span>` +
      `<span>status: <b>${escapeHtml(res.status)}</b></span>` +
      `<span><b>${res.steps_executed}</b> executed</span>`;
    renderRunSteps(res.steps, res, name);
  } catch (e) {
    tl.innerHTML = `<p class="muted small">Run failed: ${escapeHtml(e.message)}</p>`;
  } finally {
    busy($("runPlayBtn"), false);
  }
}

function runTag(step) {
  const tags = [];
  const src = step.source || "";
  if (src.startsWith("skill")) tags.push(`<span class="run-tag src-skill">${escapeHtml(src)}</span>`);
  else if (src) tags.push(`<span class="run-tag src-llm">${escapeHtml(src)}</span>`);
  if (step.tool) tags.push(`<span class="run-tag tool">${escapeHtml(step.tool)}</span>`);
  if (step.high_risk) tags.push(`<span class="run-tag risk">high-risk</span>`);
  return tags.join(" ");
}

function stepCard(step, idx) {
  const status = step.status || "success";
  const gate =
    status === "blocked"
      ? `<div class="run-gate"><button class="btn primary tiny" data-handoff="1">\u23f8 Needs a human \u2014 finish in the co-pilot \u2192</button></div>`
      : "";
  const result = step.result
    ? `<div class="run-result">${escapeHtml(step.result)}</div>`
    : status === "blocked"
    ? `<div class="run-result">Paused before execution \u2014 this step must be approved by a person.</div>`
    : "";
  return `<div class="run-step ${status}">
    <div class="run-step-head">
      <span class="run-step-num">${idx}</span>
      <span class="run-step-name">${escapeHtml(step.name)}</span>
      ${runTag(step)}
    </div>
    ${step.action ? `<div class="run-action">${escapeHtml(step.action)}</div>` : ""}
    ${result}
    ${gate}
  </div>`;
}

// Reveal steps one at a time so you can watch the skill "run".
function renderRunSteps(steps, res, name) {
  const tl = $("runTimeline");
  tl.innerHTML = "";
  let i = 0;
  const reveal = () => {
    if (i >= steps.length) return;
    const holder = document.createElement("div");
    holder.innerHTML = stepCard(steps[i], i + 1);
    const card = holder.firstElementChild;
    tl.appendChild(card);
    const hb = card.querySelector("[data-handoff]");
    if (hb) hb.addEventListener("click", () => handoffToCopilot(name, res.summary));
    tl.scrollTop = tl.scrollHeight;
    i += 1;
    setTimeout(reveal, 650);
  };
  reveal();
}

// A high-risk step can't run headless: load the skill into the co-pilot to finish.
function handoffToCopilot(name, summary) {
  $("runModal").hidden = true;
  setView("studio");
  state.taskName = name;
  state.schema = null;
  const desc = $("desc");
  if (desc) desc.value = summary || name;
  loadSkillReport(name);
  toast(`Loaded \u201c${name}\u201d into the co-pilot \u2014 click Start co-pilot to finish the high-risk step with approval.`, 6000);
}

