async function loadShellTool() {
  try {
    const st = await api("/api/shell/status");
    const badge = st.enabled
      ? `<span class="pill on">enabled</span>`
      : `<span class="pill off">disabled</span>`;
    $("shellStatus").innerHTML =
      `${badge} scripts dir <code>${escapeHtml(st.scripts_dir)}</code> · timeout ${st.timeout}s` +
      (st.enabled ? "" : ` · set <code>SHELL_TOOL_ENABLED=1</code> to run`);
    $("shellCmd").disabled = !st.enabled;
    $("shellRunBtn").disabled = !st.enabled;
    renderScripts(st.scripts || [], st.enabled);
  } catch (e) {
    $("shellStatus").textContent = "Shell tool status unavailable.";
  }
}

function renderScripts(scripts, enabled) {
  const box = $("scriptList");
  if (!scripts.length) {
    box.innerHTML = `<p class="muted small">No scripts found in the registry.</p>`;
    return;
  }
  box.innerHTML = scripts
    .map(
      (s) => `<div class="script-item">
        <code>${escapeHtml(s.name)}</code>
        <input class="script-args" data-script="${escapeHtml(s.name)}" type="text" placeholder="flags, e.g. -Name World" ${enabled ? "" : "disabled"} />
        <button class="btn ghost tiny" data-runscript="${escapeHtml(s.name)}" ${enabled ? "" : "disabled"}>▷ Invoke</button>
      </div>`
    )
    .join("");
  box.querySelectorAll("[data-runscript]").forEach((b) =>
    b.addEventListener("click", () => runScript(b.dataset.runscript))
  );
}

function showShellOut(res) {
  const out = $("shellOut");
  out.hidden = false;
  if (res.error) {
    out.textContent = `✗ ${res.error}`;
    return;
  }
  const head = `$ ${res.command}\n(exit ${res.exit_code})`;
  const body = (res.stdout || res.stderr || "(no output)").trimEnd();
  out.textContent = `${head}\n\n${body}`;
}

async function runShellCommand() {
  const command = $("shellCmd").value.trim();
  if (!command) return toast("Type a command first.");
  busy($("shellRunBtn"), true, "Running…");
  try {
    const res = await api("/api/shell/run", {
      method: "POST",
      body: JSON.stringify({ command }),
    });
    showShellOut(res);
  } catch (e) {
    toast("Command failed: " + e.message);
  } finally {
    busy($("shellRunBtn"), false);
  }
}

async function runScript(name) {
  const field = document.querySelector(`.script-args[data-script="${CSS.escape(name)}"]`);
  const raw = (field && field.value.trim()) || "";
  const args = raw ? raw.split(/\s+/) : [];
  try {
    const res = await api("/api/shell/script", {
      method: "POST",
      body: JSON.stringify({ name, args }),
    });
    showShellOut(res);
  } catch (e) {
    toast("Script failed: " + e.message);
  }
}

