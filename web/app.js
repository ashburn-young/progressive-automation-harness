// Parse the optional "Inputs (JSON)" field; returns {} when empty/blank.
function readRunInputs() {
  const raw = ($("runInputs") && $("runInputs").value || "").trim();
  if (!raw) return {};
  try {
    const parsed = JSON.parse(raw);
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) return parsed;
    toast("Inputs must be a JSON object; ignoring.");
  } catch (e) {
    toast("Inputs JSON is invalid; ignoring. " + e.message);
  }
  return {};
}

async function runSkill() {
  if (!state.taskName) return toast("Pick or generate a workflow first.");
  busy($("runBtn"), true, "Running…");
  try {
    const inputs = readRunInputs();
    const res = await api(`/api/skill-run?name=${encodeURIComponent(state.taskName)}`, {
      method: "POST",
      body: JSON.stringify({ inputs }),
    });
    if (!res.ran && res.status !== "blocked") {
      toast(res.reason || "Nothing to run.");
      return;
    }
    if (res.status === "blocked") {
      toast(`Ran up to high-risk step "${res.blocked_step}". A human is required there.`, 7000);
    } else {
      toast(`Ran "${res.task_name}" headlessly: ${res.steps_executed} step(s) executed.`, 7000);
    }
  } catch (e) {
    toast("Run failed: " + e.message);
  } finally {
    busy($("runBtn"), false);
  }
}

// ---------- utils ----------
function deDash(s) {
  return (s || "").replace(/\s*[\u2014\u2013]\s*/g, ", ");
}

function escapeHtml(s) {
  return deDash(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
}

// ---------- interview ----------
function addBubble(role, text) {
  const log = $("chatLog");
  const div = document.createElement("div");
  div.className = `bubble ${role}`;
  div.textContent = deDash(text);
  log.appendChild(div);
  log.scrollTop = log.scrollHeight;
}

async function startInterview() {
  if (state.interviewId) return;
  $("chatLog").innerHTML = "";
  addBubble("assistant", "Thinking…");
  try {
    const res = await api("/api/interview/start", { method: "POST", body: "{}" });
    state.interviewId = res.interview_id;
    $("chatLog").lastChild.textContent = res.message;
  } catch (e) {
    $("chatLog").lastChild.textContent = "Could not start interview: " + e.message;
  }
}

async function sendChat() {
  const text = $("chatText").value.trim();
  if (!text || !state.interviewId) return;
  $("chatText").value = "";
  addBubble("user", text);
  addBubble("assistant", "Thinking…");
  try {
    const res = await api(`/api/interview/${state.interviewId}/message`, {
      method: "POST",
      body: JSON.stringify({ text, detail: state.detail }),
    });
    if (res.done) {
      $("chatLog").lastChild.textContent = "Great, I have enough. Compiling your plan…";
      renderPreview(res.schema, "interview");
      toast(`Plan ready: ${res.schema.steps.length} step(s). Click Start co-pilot.`, 5000);
    } else {
      $("chatLog").lastChild.textContent = res.message;
    }
  } catch (e) {
    $("chatLog").lastChild.textContent = "Error: " + e.message;
  }
}

function setMode(mode) {
  state.mode = mode;
  document.querySelectorAll(".mode-tab").forEach((t) =>
    t.classList.toggle("active", t.dataset.mode === mode)
  );
  $("describeMode").hidden = mode !== "describe";
  $("interviewMode").hidden = mode !== "interview";
  $("generateBtn").style.display = mode === "interview" ? "none" : "";
  if (mode === "interview") startInterview();
}

